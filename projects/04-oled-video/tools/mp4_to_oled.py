#!/usr/bin/env python3
"""Stream MP4/GIF through FFmpeg into SSD1306 page-packed flash frames."""
import argparse
from fractions import Fraction
import hashlib
import json
import math
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

WIDTH, HEIGHT = 128, 64
FRAME_BYTES = WIDTH * HEIGHT // 8
DEFAULT_OUTPUT = Path(__file__).resolve().parents[1] / "include" / "video_frames.h"
BAYER4 = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def fps_value(value):
    try:
        fps = Fraction(value).limit_denominator(100000)
    except (ValueError, ZeroDivisionError):
        raise argparse.ArgumentTypeError("FPS must be a number or ratio, e.g. 10 or 30000/1001")
    if not Fraction(1, 10) <= fps <= 60:
        raise argparse.ArgumentTypeError("FPS must be between 0.1 and 60")
    return fps


def positive_seconds(value):
    try:
        seconds = float(value)
    except ValueError:
        raise argparse.ArgumentTypeError("Seconds must be a positive finite number")
    if not math.isfinite(seconds) or seconds <= 0:
        raise argparse.ArgumentTypeError("Seconds must be a positive finite number")
    return seconds


def find_ffmpeg(explicit=None):
    executable = shutil.which(explicit or "ffmpeg")
    if not executable:
        raise ValueError("FFmpeg not found. Add it to PATH or use --ffmpeg PATH_TO_FFMPEG")
    return executable


def monochrome(gray, method="ordered", threshold=128, invert=False):
    if len(gray) != WIDTH * HEIGHT:
        raise ValueError("A grayscale frame must contain exactly 8192 bytes")
    if method not in ("ordered", "threshold") or not 0 <= threshold <= 255:
        raise ValueError("Invalid monochrome settings")
    pixels = bytearray(WIDTH * HEIGHT)
    for y in range(HEIGHT):
        for x in range(WIDTH):
            cutoff = BAYER4[y % 4][x % 4] * 16 + 8 if method == "ordered" else threshold
            pixels[y * WIDTH + x] = (gray[y * WIDTH + x] >= cutoff) ^ invert
    return pixels


def pack_ssd1306(pixels):
    """Horizontal columns within each 8-row page; LSB is the upper pixel."""
    if len(pixels) != WIDTH * HEIGHT or any(p not in (0, 1) for p in pixels):
        raise ValueError("Expected 8192 binary pixels (0 or 1)")
    packed = bytearray(FRAME_BYTES)
    for y in range(HEIGHT):
        page = (y // 8) * WIDTH
        mask = 1 << (y % 8)
        for x in range(WIDTH):
            if pixels[y * WIDTH + x]:
                packed[page + x] |= mask
    return bytes(packed)


def video_filter(fps, fit):
    # Normalize sample aspect ratio before fitting; output pixels are square.
    filters = [f"fps={fps.numerator}/{fps.denominator}", "scale=iw*sar:ih", "setsar=1"]
    if fit == "crop":
        filters += ["scale=128:64:force_original_aspect_ratio=increase:flags=lanczos", "crop=128:64"]
    else:
        filters += ["scale=128:64:force_original_aspect_ratio=decrease:flags=lanczos",
                    "pad=128:64:(ow-iw)/2:(oh-ih)/2:color=black"]
    return ",".join(filters + ["format=gray"])


def read_frame(stream):
    # A pipe read can return a short chunk even though the frame is not complete.
    chunks = bytearray()
    while len(chunks) < WIDTH * HEIGHT:
        chunk = stream.read(WIDTH * HEIGHT - len(chunks))
        if not chunk:
            break
        chunks.extend(chunk)
    if chunks and len(chunks) != WIDTH * HEIGHT:
        raise ValueError(f"Truncated FFmpeg frame: {len(chunks)} bytes")
    return bytes(chunks)


def write_header(binary_path, destination, count, fps):
    with destination.open("w", encoding="utf-8", newline="\n") as output:
        output.write("// Generated by tools/mp4_to_oled.py. Re-run the converter to replace.\n")
        output.write("#pragma once\n#include <Arduino.h>\n\n")
        constants = {"VIDEO_WIDTH": WIDTH, "VIDEO_HEIGHT": HEIGHT,
                     "VIDEO_FRAME_BYTES": FRAME_BYTES, "VIDEO_FRAME_COUNT": count,
                     "VIDEO_FPS_NUM": fps.numerator, "VIDEO_FPS_DEN": fps.denominator}
        for name, value in constants.items():
            output.write(f"static constexpr uint32_t {name} = {value};\n")
        output.write("\nstatic const uint8_t VIDEO_FRAMES[VIDEO_FRAME_COUNT][VIDEO_FRAME_BYTES] PROGMEM = {\n")
        with binary_path.open("rb") as frames:
            for index in range(count):
                frame = frames.read(FRAME_BYTES)
                if len(frame) != FRAME_BYTES:
                    raise ValueError("Internal frame size mismatch")
                output.write(f"  {{ // Frame {index}\n")
                for start in range(0, FRAME_BYTES, 16):
                    output.write("    " + ", ".join(f"0x{b:02X}" for b in frame[start:start + 16]) + ",\n")
                output.write("  },\n")
        output.write("};\n")


def convert(args):
    source = args.input.resolve()
    destination = args.output.resolve()
    if not source.is_file():
        raise ValueError(f"Input file not found: {source}")
    if source == destination:
        raise ValueError("Input and output must be different files")
    if args.flash_budget <= 0 or args.firmware_reserve < 0 or args.firmware_reserve >= args.flash_budget:
        raise ValueError("Require 0 <= firmware reserve < flash budget")
    ffmpeg = find_ffmpeg(args.ffmpeg)
    destination.parent.mkdir(parents=True, exist_ok=True)
    command = [ffmpeg, "-hide_banner", "-loglevel", "error", "-nostdin"]
    if source.suffix.lower() == ".gif":
        command += ["-ignore_loop", "1"]
    command += ["-i", str(source), "-map", "0:v:0", "-an", "-sn", "-dn",
                "-vf", video_filter(args.fps, args.fit)]
    if args.seconds is not None:
        command += ["-t", str(args.seconds)]
    command += ["-fps_mode", "passthrough", "-threads", "1", "-pix_fmt", "gray", "-f", "rawvideo", "pipe:1"]
    count = 0
    warned = False
    digest = hashlib.sha256()
    # Disk spool keeps Python memory bounded, even for a long input.
    with tempfile.TemporaryDirectory(prefix="oled-", dir=destination.parent) as temp:
        temp = Path(temp)
        binary = temp / "frames.bin"
        with (temp / "ffmpeg.log").open("w+b") as errors, binary.open("wb") as frames:
            process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=errors)
            try:
                while True:
                    gray = read_frame(process.stdout)
                    if not gray:
                        break
                    frame = pack_ssd1306(monochrome(gray, args.method, args.threshold, args.invert))
                    frames.write(frame)
                    digest.update(frame)
                    count += 1
                    if count * FRAME_BYTES + args.firmware_reserve > args.flash_budget and not warned:
                        print("WARNING: Video + firmware reserve exceeds the application partition. "
                              "Reduce --seconds or --fps; the final PlatformIO build is authoritative.", file=sys.stderr)
                        warned = True
                    if warned and args.strict_size:
                        raise ValueError("--strict-size: flash estimate exceeded; existing header preserved")
                return_code = process.wait()
                if return_code:
                    errors.seek(0)
                    raise ValueError("FFmpeg failed: " + errors.read(8192).decode("utf-8", "replace"))
            finally:
                process.stdout.close()
                if process.poll() is None:
                    process.kill()
                    process.wait()
        if count == 0:
            raise ValueError("No frames decoded; check duration, FPS, and the input video")
        new_header = temp / "video_frames.h"
        write_header(binary, new_header, count, args.fps)
        new_header.replace(destination)  # Failed conversions never truncate the old header.
    summary = {"frames": count, "width": WIDTH, "height": HEIGHT,
               "bytes_per_frame": FRAME_BYTES, "video_flash_bytes": count * FRAME_BYTES,
               "fps_num": args.fps.numerator, "fps_den": args.fps.denominator,
               "duration_seconds": float(Fraction(count, 1) / args.fps),
               "flash_budget": args.flash_budget, "firmware_reserve": args.firmware_reserve,
               "estimated_total_bytes": count * FRAME_BYTES + args.firmware_reserve,
               "over_budget": warned, "fit": args.fit, "method": args.method,
               "invert": args.invert, "packed_sha256": digest.hexdigest()}
    destination.with_suffix(".json").write_text(json.dumps(summary, indent=2) + "\n", encoding="utf-8")
    print(f"Frames: {count} | FPS: {float(args.fps):.3f} | Duration: {summary['duration_seconds']:.3f}s")
    print(f"Each frame: {FRAME_BYTES} bytes | Video flash: {count * FRAME_BYTES:,} bytes")
    print(f"Estimated app: {summary['estimated_total_bytes']:,} / {args.flash_budget:,} bytes (includes reserve)")
    print(f"Header: {destination}")
    return summary


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("input", type=Path, help="Input MP4 or GIF")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--fps", type=fps_value, default=Fraction(10, 1))
    parser.add_argument("--seconds", type=positive_seconds, help="Limit output duration; default: whole input")
    parser.add_argument("--fit", choices=("crop", "letterbox"), default="letterbox")
    parser.add_argument("--method", choices=("ordered", "threshold"), default="ordered")
    parser.add_argument("--threshold", type=int, choices=range(256), default=128, metavar="0..255")
    parser.add_argument("--invert", action="store_true")
    parser.add_argument("--ffmpeg", help="FFmpeg executable path, including paths with spaces")
    parser.add_argument("--flash-budget", type=int, default=1310720, help="Application partition bytes, NOT total chip flash")
    parser.add_argument("--firmware-reserve", type=int, default=327680, help="Conservative bytes reserved for firmware/libraries")
    parser.add_argument("--strict-size", action="store_true", help="Fail instead of warning when the estimate is too large")
    args = parser.parse_args(argv)
    try:
        convert(args)
    except (ValueError, OSError) as error:
        parser.exit(1, f"ERROR: {error}\n")


if __name__ == "__main__":
    main()
